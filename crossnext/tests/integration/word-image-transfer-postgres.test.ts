import { Client } from "pg";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import {
  buildCombinedWordImageImportSql,
  buildWordImageFlagsImportSql,
  buildWordImageImportSql,
  type WordImageTransferRow,
} from "@/lib/wordImageTransfer";

// Only session-local temporary tables are touched, even when using the local app database.
describe.skipIf(!process.env.MEGACROSS_IMAGE_TRANSFER_TEST_DATABASE_URL)("word image PostgreSQL transfer", () => {
  const db = new Client({ connectionString: process.env.MEGACROSS_IMAGE_TRANSFER_TEST_DATABASE_URL });
  const row: WordImageTransferRow = {
    wordId: "10",
    word: "кот",
    language: "ru",
    imageGeneratedAt: "2026-11-04T12:00:00.123456Z",
    fileName: "кот-512x512-1.png",
    mimeType: "image/png",
    storageRelPath: `10/${"a".repeat(64)}.png`,
    sha256: "a".repeat(64),
    sizeBytes: "1234",
    width: 512,
    height: 512,
    aspectRatio: "1.000000",
    needsReview: true,
    createdAt: "2026-11-04T12:00:00.123456Z",
    updatedAt: "2026-11-04T12:00:00.123456Z",
  };
  beforeAll(async () => {
    await db.connect();
    await db.query(`
      CREATE TEMP TABLE language (id integer PRIMARY KEY, code text);
      CREATE TEMP TABLE word_v (id bigint PRIMARY KEY, word_text text, "langId" integer, "isImageable" boolean DEFAULT false, "imageGeneratedAt" timestamp);
      CREATE TEMP TABLE scanword_word_images (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "wordId" bigint REFERENCES word_v(id), "fileName" text, "mimeType" text,
        "storageRelPath" text, sha256 text, "sizeBytes" bigint, width integer, height integer,
        "aspectRatio" numeric, "needsReview" boolean, "createdAt" timestamp, "updatedAt" timestamp,
        UNIQUE ("wordId", sha256)
      );
    `);
    const check = await db.query(
      "SELECT to_regclass('pg_temp.word_v') IS NOT NULL AND to_regclass('pg_temp.scanword_word_images') IS NOT NULL AS isolated",
    );
    expect(check.rows[0].isolated).toBe(true);
  });
  beforeEach(async () => {
    await db.query("ROLLBACK");
    await db.query(`TRUNCATE pg_temp.scanword_word_images, pg_temp.word_v, pg_temp.language RESTART IDENTITY;
      INSERT INTO pg_temp.language VALUES (1, 'ru');
      INSERT INTO pg_temp.word_v (id,word_text,"langId") VALUES (10,'кот',1);`);
  });
  afterAll(async () => {
    await db.query("ROLLBACK");
    await db.end();
  });
  it("imports metadata with new IDs and is safe to repeat", async () => {
    await db.query(buildWordImageImportSql([row]));
    const first = (await db.query("SELECT * FROM pg_temp.scanword_word_images")).rows;
    expect(first).toHaveLength(1);
    expect(first[0]).toMatchObject({
      wordId: "10",
      fileName: row.fileName,
      storageRelPath: row.storageRelPath,
      needsReview: true,
    });
    const dates = await db.query(
      "SELECT to_char(\"createdAt\", 'YYYY-MM-DD HH24:MI:SS.US') AS exact FROM pg_temp.scanword_word_images",
    );
    expect(dates.rows[0].exact).toBe("2026-11-04 12:00:00.123456");
    await db.query(buildWordImageImportSql([row]));
    expect((await db.query("SELECT id FROM pg_temp.scanword_word_images")).rows).toEqual([{ id: first[0].id }]);
    expect((await db.query('SELECT "isImageable" FROM pg_temp.word_v')).rows[0].isImageable).toBe(true);
  });
  it.each([
    { wordId: "11", storageRelPath: "11/image.png" },
    { word: "собака" },
    { language: "uk" },
  ])("aborts the complete import when a word does not match %j", async (mismatch) => {
    await expect(db.query(buildWordImageImportSql([{ ...row, ...mismatch }]))).rejects.toThrow(
      "Destination words do not match",
    );
    await db.query("ROLLBACK");
    expect((await db.query("SELECT count(*)::int AS n FROM pg_temp.scanword_word_images")).rows[0].n).toBe(0);
  });
  it("preserves an existing production generation date", async () => {
    await db.query(`UPDATE pg_temp.word_v SET "imageGeneratedAt"='2025-01-01'`);
    await db.query(buildWordImageImportSql([row]));
    const result = await db.query(`SELECT "imageGeneratedAt"::text AS date FROM pg_temp.word_v`);
    expect(result.rows[0].date).toBe("2025-01-01 00:00:00");
  });
  it("transfers imageable flags for words with no image and no generation date", async () => {
    const sql = buildWordImageFlagsImportSql([{ ...row, isImageable: true, imageGeneratedAt: null }]);
    await db.query(sql);
    await db.query(sql);
    const word = (await db.query('SELECT "isImageable", "imageGeneratedAt" FROM pg_temp.word_v')).rows[0];
    expect(word).toEqual({ isImageable: true, imageGeneratedAt: null });
    expect((await db.query("SELECT count(*)::int AS n FROM pg_temp.scanword_word_images")).rows[0].n).toBe(0);
  });
  it("fills a missing generation date without clearing destination flags or overwriting a date", async () => {
    await db.query('UPDATE pg_temp.word_v SET "isImageable"=true');
    await db.query(buildWordImageFlagsImportSql([{ ...row, isImageable: false }]));
    const word = (
      await db.query(
        `SELECT "isImageable", to_char("imageGeneratedAt", 'YYYY-MM-DD HH24:MI:SS.US') AS exact FROM pg_temp.word_v`,
      )
    ).rows[0];
    expect(word).toEqual({ isImageable: true, exact: "2026-11-04 12:00:00.123456" });
    await db.query(
      buildWordImageFlagsImportSql([{ ...row, isImageable: true, imageGeneratedAt: "2026-12-01T00:00:00.000Z" }]),
    );
    const date = (
      await db.query(`SELECT to_char("imageGeneratedAt", 'YYYY-MM-DD HH24:MI:SS.US') AS exact FROM pg_temp.word_v`)
    ).rows[0].exact;
    expect(date).toBe("2026-11-04 12:00:00.123456");
  });
  it("rolls back word flag updates when dictionary identity does not match", async () => {
    await expect(
      db.query(buildWordImageFlagsImportSql([{ ...row, word: "собака", isImageable: true }])),
    ).rejects.toThrow("Destination words do not match");
    await db.query("ROLLBACK");
    expect((await db.query('SELECT "isImageable" FROM pg_temp.word_v')).rows[0].isImageable).toBe(false);
  });
  it("imports images and flags for words without images in one repeatable transaction", async () => {
    await db.query(`INSERT INTO pg_temp.word_v (id,word_text,"langId") VALUES (11,'собака',1)`);
    const sql = buildCombinedWordImageImportSql(
      [row],
      [
        { ...row, isImageable: true },
        { ...row, wordId: "11", word: "собака", isImageable: true, imageGeneratedAt: null },
      ],
    );
    expect(sql.match(/^BEGIN;$/gm)).toHaveLength(1);
    expect(sql.match(/^COMMIT;$/gm)).toHaveLength(1);
    await db.query(sql);
    await db.query(sql);
    expect((await db.query("SELECT count(*)::int AS n FROM pg_temp.scanword_word_images")).rows[0].n).toBe(1);
    expect((await db.query('SELECT id::text, "isImageable" FROM pg_temp.word_v ORDER BY id')).rows).toEqual([
      { id: "10", isImageable: true },
      { id: "11", isImageable: true },
    ]);
  });
  it("rolls back an already inserted image when the subsequent word flag import fails", async () => {
    const sql = buildCombinedWordImageImportSql([row], [{ ...row, word: "другое слово", isImageable: true }]);
    await expect(db.query(sql)).rejects.toThrow("Destination words do not match");
    await db.query("ROLLBACK");
    expect((await db.query("SELECT count(*)::int AS n FROM pg_temp.scanword_word_images")).rows[0].n).toBe(0);
    expect((await db.query('SELECT "isImageable", "imageGeneratedAt" FROM pg_temp.word_v')).rows[0]).toEqual({
      isImageable: false,
      imageGeneratedAt: null,
    });
  });
});
